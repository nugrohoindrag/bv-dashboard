func (h *Handler) listPermits(w http.ResponseWriter, r *http.Request) {
	page, err := httpx.ParsePage(r)
	if err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	var f PermitFilter
	f.PropertyID, _ = httpx.QueryUUID(r, "property_id")
	f.VehicleID, _ = httpx.QueryUUID(r, "vehicle_id")
	f.Statuses = httpx.QueryCSV(r, "status")
	f.Q = r.URL.Query().Get("q")
	items, next, err := h.Svc.ListParkingPermits(r.Context(), f, page)
	if err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	httpx.WriteJSON(w, http.StatusOK, httpx.NewList(items, next))
}

